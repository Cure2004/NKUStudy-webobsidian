/** 英文词条表：目前仅回退到 key，占位以便日后扩展。 */
const en: Record<string, string> = {};

const dictionaries: Record<Locale, Record<string, string>> = { 'zh-CN': zh, en };

/** 用 vars 替换 `{name}` 占位符。 */
function interpolate(template: string, vars?: Vars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (m, key) =>
    Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : m,
  );
}

/**
 * 翻译函数：以英文原文为 key，返回当前语言的译文。
 * 未命中时回退到 key 本身（英文），保证界面不会出现空白。
 */
export function t(key: string, vars?: Vars): string {
  const dict = dictionaries[currentLocale] ?? zh;
  const hit = dict[key];
  if (hit === undefined) return interpolate(key, vars);
  return interpolate(hit, vars);
}

